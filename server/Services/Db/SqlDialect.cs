using System.Text;
using QosriStudio.Server.Models;

namespace QosriStudio.Server.Services.Db;

/// <summary>How each database spells names, paging and schema changes.</summary>
public sealed partial class SqlDialect
{
    public DbProvider Provider { get; }
    private SqlDialect(DbProvider p) => Provider = p;

    private static readonly Dictionary<DbProvider, SqlDialect> All = Enum.GetValues<DbProvider>().ToDictionary(p => p, p => new SqlDialect(p));
    public static SqlDialect For(DbProvider p) => All[p];

    public List<string> CommonTypes => Provider switch
    {
        DbProvider.SqlServer => ["int", "bigint", "smallint", "tinyint", "bit", "decimal(18,2)", "money", "float", "nvarchar(50)", "nvarchar(100)", "nvarchar(255)", "nvarchar(max)", "varchar(255)", "char(10)", "date", "datetime2", "datetime", "time", "datetimeoffset", "uniqueidentifier", "varbinary(max)", "xml"],
        DbProvider.PostgreSql => ["integer", "bigint", "smallint", "boolean", "numeric(18,2)", "real", "double precision", "varchar(50)", "varchar(100)", "varchar(255)", "text", "char(10)", "date", "timestamp", "timestamptz", "time", "uuid", "jsonb", "json", "bytea"],
        DbProvider.MySql => ["int", "bigint", "smallint", "tinyint(1)", "decimal(18,2)", "float", "double", "varchar(50)", "varchar(100)", "varchar(255)", "text", "longtext", "char(10)", "date", "datetime", "timestamp", "time", "json", "blob"],
        DbProvider.Oracle => ["NUMBER(10)", "NUMBER(19)", "NUMBER(1)", "NUMBER(18,2)", "FLOAT", "VARCHAR2(50)", "VARCHAR2(100)", "VARCHAR2(255)", "VARCHAR2(4000)", "NVARCHAR2(255)", "CHAR(10)", "CLOB", "DATE", "TIMESTAMP", "BLOB", "RAW(16)"],
        _ => ["INTEGER", "TEXT", "REAL", "NUMERIC", "BLOB"],
    };

    public string Quote(string name) => Provider switch
    {
        DbProvider.SqlServer => "[" + name.Replace("]", "]]") + "]",
        DbProvider.MySql => "`" + name.Replace("`", "``") + "`",
        _ => "\"" + name.Replace("\"", "\"\"") + "\"",
    };

    public string Table(string? schema, string name) => string.IsNullOrEmpty(schema) || Provider is DbProvider.MySql or DbProvider.Sqlite ? Quote(name) : Quote(schema) + "." + Quote(name);

    public string Param(int i) => Provider == DbProvider.Oracle ? $":p{i}" : $"@p{i}";

    public string Page(string select, string orderBy, int offset, int limit) => Provider switch
    {
        DbProvider.SqlServer or DbProvider.Oracle => $"{select} ORDER BY {orderBy} OFFSET {offset} ROWS FETCH NEXT {limit} ROWS ONLY",
        _ => $"{select} ORDER BY {orderBy} LIMIT {limit} OFFSET {offset}",
    };

    /// <summary>Expression that turns a column into text for searching.</summary>
    public string AsText(string column) => Provider switch
    {
        DbProvider.SqlServer => $"CAST({column} AS nvarchar(max))",
        DbProvider.PostgreSql => $"CAST({column} AS text)",
        DbProvider.MySql => $"CAST({column} AS char)",
        DbProvider.Oracle => $"TO_CHAR({column})",
        _ => $"CAST({column} AS TEXT)",
    };

    public string Like => Provider == DbProvider.PostgreSql ? "ILIKE" : "LIKE";
    public string Lower(string e) => Provider == DbProvider.PostgreSql ? e : $"LOWER({e})";

    // ------------------------------------------------------------------ DDL

    public string ColumnSql(DbsColumnDef c, bool inCreate, bool singlePk)
    {
        var sb = new StringBuilder(Quote(c.Name)).Append(' ');
        if (c.Identity)
        {
            switch (Provider)
            {
                case DbProvider.SqlServer: sb.Append(c.Type).Append(" IDENTITY(1,1)"); break;
                case DbProvider.PostgreSql: sb.Append(c.Type).Append(" GENERATED BY DEFAULT AS IDENTITY"); break;
                case DbProvider.MySql: sb.Append(c.Type).Append(" AUTO_INCREMENT"); break;
                case DbProvider.Oracle: sb.Append(c.Type).Append(" GENERATED BY DEFAULT AS IDENTITY"); break;
                default: sb.Append("INTEGER"); break;
            }
        }
        else sb.Append(c.Type);
        if (!string.IsNullOrWhiteSpace(c.Default) && !c.Identity) sb.Append(" DEFAULT ").Append(c.Default.Trim());
        sb.Append(c.Nullable && !c.PrimaryKey ? " NULL" : " NOT NULL");
        if (Provider == DbProvider.Oracle && c.Nullable && !c.PrimaryKey) sb.Length -= " NULL".Length; // Oracle: nullable is the default
        if (inCreate && singlePk && c.PrimaryKey)
        {
            sb.Append(" PRIMARY KEY");
            if (Provider == DbProvider.Sqlite && c.Identity) sb.Append(" AUTOINCREMENT");
        }
        return sb.ToString();
    }

    /// <summary>Turns a requested change into the statements that make it. Throws a friendly message when the database can't do it.</summary>
    public List<string> Ddl(DdlChange ch, DbSchema? schema)
    {
        var t = Table(ch.Schema, ch.Table ?? "");
        string N(string? x) => Quote(x ?? throw new StudioException("A name is missing."));
        switch (ch.Kind)
        {
            case "createTable":
            {
                var cols = ch.Columns ?? [];
                if (cols.Count == 0) throw new StudioException("Add at least one column.");
                if (cols.Select(c => c.Name.ToLowerInvariant()).Distinct().Count() != cols.Count) throw new StudioException("Two columns have the same name.");
                var pk = cols.Where(c => c.PrimaryKey).ToList();
                var single = pk.Count == 1;
                var lines = cols.Select(c => "  " + ColumnSql(c, true, single)).ToList();
                if (pk.Count > 1) lines.Add("  PRIMARY KEY (" + string.Join(", ", pk.Select(c => Quote(c.Name))) + ")");
                return [$"CREATE TABLE {t} (\n{string.Join(",\n", lines)}\n)"];
            }
            case "dropTable": return [$"DROP TABLE {t}"];
            case "truncateTable":
                return [Provider == DbProvider.Sqlite ? $"DELETE FROM {t}" : $"TRUNCATE TABLE {t}"];
            case "renameTable":
                return [Provider switch
                {
                    DbProvider.SqlServer => $"EXEC sp_rename '{Lit(ch.Schema)}.{Lit(ch.Table)}', '{Lit(ch.NewName)}'",
                    DbProvider.MySql => $"RENAME TABLE {t} TO {N(ch.NewName)}",
                    DbProvider.Oracle => $"ALTER TABLE {t} RENAME TO {N(ch.NewName)}",
                    _ => $"ALTER TABLE {t} RENAME TO {N(ch.NewName)}",
                }];
            case "addColumn":
            {
                var c = ch.Column ?? throw new StudioException("The column is missing.");
                if (Provider == DbProvider.Sqlite && c.PrimaryKey) throw new StudioException("SQLite can't add a key column to an existing table.");
                var col = ColumnSql(c with { PrimaryKey = false }, false, false);
                if (!c.Nullable && string.IsNullOrWhiteSpace(c.Default) && !c.Identity && (schema?.Tables.FirstOrDefault(x => x.Name == ch.Table && x.Schema == (ch.Schema ?? ""))?.Rows ?? 0) > 0)
                    throw new StudioException("The table already has rows, so a required column needs a default value (or allow it to be empty).");
                var add = Provider switch
                {
                    DbProvider.SqlServer => $"ALTER TABLE {t} ADD {col}",
                    DbProvider.Oracle => $"ALTER TABLE {t} ADD ({col})",
                    _ => $"ALTER TABLE {t} ADD COLUMN {col}",
                };
                return [add];
            }
            case "dropColumn":
                return [Provider == DbProvider.Oracle || Provider == DbProvider.SqlServer ? $"ALTER TABLE {t} DROP COLUMN {N(ch.OldName)}" : $"ALTER TABLE {t} DROP COLUMN {N(ch.OldName)}"];
            case "renameColumn":
                return [Provider switch
                {
                    DbProvider.SqlServer => $"EXEC sp_rename '{Lit(ch.Schema)}.{Lit(ch.Table)}.{Lit(ch.OldName)}', '{Lit(ch.NewName)}', 'COLUMN'",
                    _ => $"ALTER TABLE {t} RENAME COLUMN {N(ch.OldName)} TO {N(ch.NewName)}",
                }];
            case "alterColumn":
            {
                var c = ch.Column ?? throw new StudioException("The column is missing.");
                var q = N(c.Name);
                var current = schema?.Tables.FirstOrDefault(x => x.Name == ch.Table && x.Schema == (ch.Schema ?? ""))?.Columns.FirstOrDefault(x => x.Name == c.Name);
                switch (Provider)
                {
                    case DbProvider.SqlServer:
                    {
                        var list = new List<string>();
                        var dfName = $"DF_{ch.Table}_{c.Name}";
                        if (current?.Default != c.Default)
                        {
                            list.Add($"""
                                DECLARE @df sysname = (SELECT d.name FROM sys.default_constraints d JOIN sys.columns c ON c.object_id = d.parent_object_id AND c.column_id = d.parent_column_id WHERE d.parent_object_id = OBJECT_ID('{Lit(ch.Schema)}.{Lit(ch.Table)}') AND c.name = '{Lit(c.Name)}');
                                IF @df IS NOT NULL EXEC('ALTER TABLE {t.Replace("'", "''")} DROP CONSTRAINT [' + @df + ']')
                                """);
                        }
                        list.Add($"ALTER TABLE {t} ALTER COLUMN {q} {c.Type} {(c.Nullable ? "NULL" : "NOT NULL")}");
                        if (current?.Default != c.Default && !string.IsNullOrWhiteSpace(c.Default))
                            list.Add($"ALTER TABLE {t} ADD CONSTRAINT {Quote(dfName)} DEFAULT {c.Default} FOR {q}");
                        return list;
                    }
                    case DbProvider.PostgreSql:
                    {
                        var list = new List<string> { $"ALTER TABLE {t} ALTER COLUMN {q} TYPE {c.Type} USING {q}::{c.Type}" };
                        list.Add($"ALTER TABLE {t} ALTER COLUMN {q} {(c.Nullable ? "DROP NOT NULL" : "SET NOT NULL")}");
                        list.Add(string.IsNullOrWhiteSpace(c.Default) ? $"ALTER TABLE {t} ALTER COLUMN {q} DROP DEFAULT" : $"ALTER TABLE {t} ALTER COLUMN {q} SET DEFAULT {c.Default}");
                        return list;
                    }
                    case DbProvider.MySql:
                        return [$"ALTER TABLE {t} MODIFY COLUMN {ColumnSql(c with { PrimaryKey = false }, false, false)}"];
                    case DbProvider.Oracle:
                    {
                        var parts = new StringBuilder($"{q} {c.Type}");
                        parts.Append(" DEFAULT ").Append(string.IsNullOrWhiteSpace(c.Default) ? "NULL" : c.Default);
                        if (current is null || current.Nullable != c.Nullable) parts.Append(c.Nullable ? " NULL" : " NOT NULL");
                        return [$"ALTER TABLE {t} MODIFY ({parts})"];
                    }
                    default:
                        throw new StudioException("SQLite can't change a column's type. Create a new column, copy the data across and drop the old one.");
                }
            }
            case "setPrimaryKey":
            {
                if (Provider == DbProvider.Sqlite) throw new StudioException("SQLite can't change the key of an existing table.");
                var list = new List<string>();
                var table = schema?.Tables.FirstOrDefault(x => x.Name == ch.Table && x.Schema == (ch.Schema ?? ""));
                if (table?.PkName is { } old)
                    list.Add(Provider == DbProvider.MySql ? $"ALTER TABLE {t} DROP PRIMARY KEY" : $"ALTER TABLE {t} DROP CONSTRAINT {Quote(old)}");
                if (ch.KeyColumns is { Count: > 0 } keys)
                    list.Add($"ALTER TABLE {t} ADD CONSTRAINT {Quote(ch.ConstraintName ?? $"PK_{ch.Table}")} PRIMARY KEY ({string.Join(", ", keys.Select(Quote))})");
                return list;
            }
            case "addForeignKey":
            {
                if (Provider == DbProvider.Sqlite) throw new StudioException("SQLite can only add relations when a table is created.");
                var cols = ch.KeyColumns ?? [];
                var refs = ch.RefColumns ?? [];
                if (cols.Count == 0 || cols.Count != refs.Count) throw new StudioException("Pick the same number of columns on both sides of the relation.");
                var name = ch.ConstraintName ?? $"FK_{ch.Table}_{ch.RefTable}";
                var del = ch.OnDelete is { Length: > 0 } d && d != "NO ACTION" ? $" ON DELETE {d}" : "";
                if (Provider == DbProvider.Oracle && del is " ON DELETE RESTRICT" or " ON DELETE SET DEFAULT") del = "";
                return [$"ALTER TABLE {t} ADD CONSTRAINT {Quote(name)} FOREIGN KEY ({string.Join(", ", cols.Select(Quote))}) REFERENCES {Table(ch.RefSchema, ch.RefTable ?? "")} ({string.Join(", ", refs.Select(Quote))}){del}"];
            }
            case "dropForeignKey":
                if (Provider == DbProvider.Sqlite) throw new StudioException("SQLite can't remove a relation from an existing table.");
                return [Provider == DbProvider.MySql ? $"ALTER TABLE {t} DROP FOREIGN KEY {N(ch.ConstraintName)}" : $"ALTER TABLE {t} DROP CONSTRAINT {N(ch.ConstraintName)}"];
            case "addIndex":
            {
                var cols = ch.KeyColumns ?? [];
                if (cols.Count == 0) throw new StudioException("Pick at least one column for the index.");
                var name = ch.ConstraintName ?? $"IX_{ch.Table}_{string.Join("_", cols)}";
                var idx = Provider is DbProvider.PostgreSql or DbProvider.Oracle && !string.IsNullOrEmpty(ch.Schema) ? Quote(name) : Quote(name);
                return [$"CREATE {(ch.Unique ? "UNIQUE " : "")}INDEX {idx} ON {t} ({string.Join(", ", cols.Select(Quote))})"];
            }
            case "dropIndex":
                return [Provider switch
                {
                    DbProvider.SqlServer => $"DROP INDEX {N(ch.ConstraintName)} ON {t}",
                    DbProvider.MySql => $"DROP INDEX {N(ch.ConstraintName)} ON {t}",
                    _ => $"DROP INDEX {Table(ch.Schema, ch.ConstraintName ?? "")}",
                }];
            case "createView":
            {
                var body = (ch.Sql ?? "").Trim().TrimEnd(';');
                if (body.Length == 0) throw new StudioException("Write the query the view shows.");
                return [$"CREATE VIEW {Table(ch.Schema, ch.NewName ?? ch.Table ?? "")} AS\n{body}"];
            }
            case "dropView": return [$"DROP VIEW {t}"];
            case "dropRoutine":
            {
                var kind = (ch.OldName ?? "Procedure").ToUpperInvariant();
                return [$"DROP {kind} {t}"];
            }
            case "createSchema":
                if (Provider is not (DbProvider.SqlServer or DbProvider.PostgreSql)) throw new StudioException("This database doesn't use schemas.");
                return [$"CREATE SCHEMA {N(ch.NewName)}"];
            default:
                return DdlMore(ch, schema);
        }
    }

    private static string Lit(string? s) => (s ?? "").Replace("'", "''");

    /// <summary>A CREATE TABLE script for an existing table, including keys, relations and indexes.</summary>
    public string Script(DbsTable table, DbSchema s)
    {
        var defs = table.Columns.Select(c => new DbsColumnDef(c.Name, c.Type, c.Nullable, c.Default, c.Identity, c.PrimaryKey)).ToList();
        var sb = new StringBuilder();
        var create = Ddl(new DdlChange("createTable", table.Schema, table.Name, Columns: defs), null)[0];
        sb.Append(create).Append(";\n");
        foreach (var fk in s.ForeignKeys.Where(f => f.Table == table.Name && f.Schema == table.Schema))
        {
            if (Provider == DbProvider.Sqlite) { sb.Append($"-- relation: ({string.Join(", ", fk.Columns)}) → {fk.RefTable} ({string.Join(", ", fk.RefColumns)})\n"); continue; }
            sb.Append(Ddl(new DdlChange("addForeignKey", table.Schema, table.Name, ConstraintName: fk.Name, KeyColumns: fk.Columns, RefSchema: fk.RefSchema, RefTable: fk.RefTable, RefColumns: fk.RefColumns, OnDelete: fk.OnDelete), null)[0]).Append(";\n");
        }
        foreach (var ix in s.Indexes.Where(i => i.Table == table.Name && i.Schema == table.Schema))
            sb.Append(Ddl(new DdlChange("addIndex", table.Schema, table.Name, ConstraintName: ix.Name, KeyColumns: ix.Columns, Unique: ix.Unique), null)[0]).Append(";\n");
        return sb.ToString();
    }
}
