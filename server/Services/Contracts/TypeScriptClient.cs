using System.Text;
using System.Text.RegularExpressions;

namespace QosriStudio.Server.Services.Contracts;

public sealed record GeneratedFile(string RelativePath, string Content, bool KeepIfExists);

/// <summary>Writes a typed client for an API: an Angular service, or a fetch-based client for React, Next.js, Vue or any other app.</summary>
public static class TypeScriptClient
{
    private static readonly HashSet<string> Reserved = new(StringComparer.Ordinal)
    {
        "Record", "Date", "Error", "Object", "Promise", "Response", "Request", "Map", "Set", "Array", "String", "Number", "Boolean", "Function", "Symbol",
        "Partial", "Required", "Readonly", "Pick", "Omit", "Event", "File", "Blob", "Headers", "URL", "Node", "Element", "Document", "Location", "History",
        "Observable", "HttpClient", "HttpParams", "HttpHeaders", "Injectable", "ApiError", "ApiService", "ApiClient", "ApiClientOptions",
    };

    private const string Banner = "// Generated by QosriStudio from the {0} API. Don't edit this file: generate it again after the API changes.\n";

    public static List<GeneratedFile> Generate(ApiContract c, string framework, bool typeScript, string outDir, string? envImport, string? envProperty, string apiName, string fetchEnvExpr)
    {
        var names = c.Types.Keys.ToDictionary(k => k, k => Reserved.Contains(k) ? "Api" + k : k, StringComparer.Ordinal);
        var files = new List<GeneratedFile>();
        if (framework == "Angular")
        {
            files.Add(new GeneratedFile($"{outDir}/api.models.ts", string.Format(Banner, apiName) + "\n" + Models(c, names), false));
            files.Add(new GeneratedFile($"{outDir}/api.service.ts", AngularService(c, names, envImport, envProperty, apiName), false));
        }
        else
        {
            var ext = typeScript ? "ts" : "js";
            files.Add(new GeneratedFile($"{outDir}/api-client.{ext}", FetchClient(c, names, typeScript, apiName), false));
            files.Add(new GeneratedFile($"{outDir}/index.{ext}", FetchIndex(fetchEnvExpr, typeScript, c.UsesAuth), true));
        }
        return files;
    }

    // ------------------------------------------------------------------ types

    private static string Models(ApiContract c, Dictionary<string, string> names)
    {
        var sb = new StringBuilder();
        foreach (var def in c.Types.Values.OrderBy(d => d.Name, StringComparer.Ordinal))
        {
            var name = names[def.Name];
            if (def.Description is not null) sb.Append($"/** {def.Description} */\n");
            if (def.Enum is not null)
            {
                if (def.StringEnum) sb.Append($"export type {name} = {string.Join(" | ", def.Enum.Select(e => $"'{e.Name}'"))};\n\n");
                else
                {
                    sb.Append($"export enum {name} {{\n");
                    foreach (var (n, v) in def.Enum) sb.Append($"  {n} = {v},\n");
                    sb.Append("}\n\n");
                }
                continue;
            }
            var tp = def.TypeParams.Count > 0 ? "<" + string.Join(", ", def.TypeParams) + ">" : "";
            sb.Append($"export interface {name}{tp} {{\n");
            foreach (var p in def.Props)
            {
                if (p.Description is not null) sb.Append($"  /** {p.Description} */\n");
                sb.Append($"  {PropName(p.JsonName)}{(p.Required ? "" : "?")}: {Ts(p.Type, names)};\n");
            }
            sb.Append("}\n\n");
        }
        return sb.ToString().TrimEnd() + "\n";
    }

    private static string PropName(string n) => Regex.IsMatch(n, @"^[A-Za-z_$][A-Za-z0-9_$]*$") ? n : $"'{n.Replace("'", "\\'")}'";

    private static string Ts(TypeRef t, Dictionary<string, string> names)
    {
        var s = t.Kind switch
        {
            "string" => t.Format == "binary" ? "Blob" : "string",
            "integer" or "number" => "number",
            "boolean" => "boolean",
            "array" => Wrap(Ts(t.Element!, names)) + "[]",
            "map" => $"Record<string, {Ts(t.Element!, names)}>",
            "ref" => (names.GetValueOrDefault(t.Name!) ?? "unknown") + (t.Args is { Count: > 0 } a ? "<" + string.Join(", ", a.Select(x => Ts(x, names))) + ">" : ""),
            "param" => t.Name!,
            _ => "unknown",
        };
        return t.Nullable && s != "unknown" ? s + " | null" : s;
    }

    private static string Wrap(string s) => s.Contains(' ') ? $"({s})" : s;

    // ------------------------------------------------------------------ operations

    private sealed record Call(string Name, string? Doc, string Signature, string ReturnType, string Method, string UrlExpr, bool HasBody, bool HasQuery, bool HasHeaders);

    private static List<(string Group, List<Call> Calls)> Calls(ApiContract c, Dictionary<string, string> names, bool typed)
    {
        string T(TypeRef t) => Ts(t, names);
        return c.Operations.GroupBy(o => o.Tag).OrderBy(g => g.Key).Select(g => (Safe(g.Key), g.Select(op =>
        {
            var args = new List<string>();
            foreach (var p in op.PathParams) args.Add(typed ? $"{Safe(p.Name)}: {T(p.Type)}" : Safe(p.Name));
            if (op.Body is not null) args.Add(typed ? $"body: {T(op.Body)}" : "body");
            if (op.QueryParams.Count > 0)
            {
                var allOptional = op.QueryParams.All(q => q.Optional);
                var shape = "{ " + string.Join("; ", op.QueryParams.Select(q => $"{PropName(q.JsonName)}{(q.Optional ? "?" : "")}: {T(q.Type)}")) + " }";
                args.Add(typed ? $"query{(allOptional ? "?" : "")}: {shape}" : "query");
            }
            if (op.HeaderParams.Count > 0)
                args.Add(typed ? "headers?: { " + string.Join("; ", op.HeaderParams.Select(h => $"{PropName(h.JsonName)}?: string")) + " }" : "headers");
            var url = "`" + Regex.Replace(op.Path.Replace("`", "\\`"), @"\{([A-Za-z0-9_]+)\}", m =>
            {
                var p = op.PathParams.FirstOrDefault(x => x.Name.Equals(m.Groups[1].Value, StringComparison.OrdinalIgnoreCase));
                return "${encodeURIComponent(String(" + Safe(p?.Name ?? m.Groups[1].Value) + "))}";
            }) + "`";
            var ret = op.Response is null ? "void" : T(op.Response);
            var doc = string.Join(" ", new[] { op.Summary, op.RequiresAuth ? "(sign-in required)" : null }.Where(x => !string.IsNullOrWhiteSpace(x)));
            return new Call(op.Name, doc.Length > 0 ? doc : null, string.Join(", ", args), ret, op.Method, url, op.Body is not null, op.QueryParams.Count > 0, op.HeaderParams.Count > 0);
        }).ToList())).ToList();
    }

    private static readonly HashSet<string> JsReserved = ["delete", "new", "default", "class", "function", "var", "let", "const", "export", "import", "in", "of", "for", "while", "do", "if", "else", "return", "switch", "case", "this", "typeof", "void", "with", "yield", "enum", "package", "private", "protected", "public", "static", "interface", "body", "query", "headers"];
    private static string Safe(string n) => JsReserved.Contains(n) ? n + "Value" : n;

    // ------------------------------------------------------------------ fetch client (React, Next.js, Vue, anything)

    private static string FetchClient(ApiContract c, Dictionary<string, string> names, bool ts, string apiName)
    {
        var sb = new StringBuilder();
        sb.Append("/* eslint-disable */\n").Append(string.Format(Banner, apiName)).Append('\n');
        if (ts) sb.Append(Models(c, names)).Append('\n');
        sb.Append(ts
            ? """
              export class ApiError extends Error {
                constructor(public readonly status: number, public readonly body: unknown) {
                  super(typeof body === 'object' && body && 'title' in body ? String((body as { title: unknown }).title) : `Request failed with status ${status}`)
                }
              }

              export interface ApiClientOptions {
                /** Address of the API, e.g. https://localhost:5001. Empty means the same site as the app. */
                baseUrl?: string
                /** Returns the sign-in token to send, if any. */
                getToken?: () => string | null | undefined | Promise<string | null | undefined>
                /** Called when the API answers 401 (not signed in or the token expired). */
                onUnauthorized?: () => void
                headers?: Record<string, string>
                fetch?: typeof fetch
              }

              type QueryValue = string | number | boolean | null | undefined
              type Query = Record<string, QueryValue | QueryValue[]>

              export function createApiClient(options: ApiClientOptions = {}) {
                const base = (options.baseUrl ?? '').replace(/\/+$/, '')
                const send = options.fetch ?? ((input: RequestInfo | URL, init?: RequestInit) => fetch(input, init))

                async function request<T>(method: string, path: string, init: { query?: object; body?: unknown; headers?: Record<string, string | undefined> } = {}): Promise<T> {
                  let url = base + path
                  if (init.query) {
                    const qs = new URLSearchParams()
                    for (const [key, value] of Object.entries(init.query as Query)) {
                      if (value == null) continue
                      if (Array.isArray(value)) value.forEach(v => { if (v != null) qs.append(key, String(v)) })
                      else qs.append(key, String(value))
                    }
                    const text = qs.toString()
                    if (text) url += (url.includes('?') ? '&' : '?') + text
                  }
                  const headers: Record<string, string> = { Accept: 'application/json', ...options.headers }
                  for (const [key, value] of Object.entries(init.headers ?? {})) if (value != null) headers[key] = value
                  if (init.body !== undefined) headers['Content-Type'] = 'application/json'
                  const token = await options.getToken?.()
                  if (token) headers.Authorization = `Bearer ${token}`
                  const res = await send(url, { method, headers, body: init.body === undefined ? undefined : JSON.stringify(init.body) })
                  const text = await res.text()
                  let data: unknown = undefined
                  if (text) { try { data = JSON.parse(text) } catch { data = text } }
                  if (res.status === 401) options.onUnauthorized?.()
                  if (!res.ok) throw new ApiError(res.status, data)
                  return data as T
                }

                return {

              """
            : """
              export class ApiError extends Error {
                constructor(status, body) {
                  super(body && typeof body === 'object' && 'title' in body ? String(body.title) : `Request failed with status ${status}`)
                  this.status = status
                  this.body = body
                }
              }

              /**
               * @param {{ baseUrl?: string, getToken?: () => any, onUnauthorized?: () => void, headers?: Record<string, string>, fetch?: typeof fetch }} options
               */
              export function createApiClient(options = {}) {
                const base = (options.baseUrl ?? '').replace(/\/+$/, '')
                const send = options.fetch ?? ((input, init) => fetch(input, init))

                async function request(method, path, init = {}) {
                  let url = base + path
                  if (init.query) {
                    const qs = new URLSearchParams()
                    for (const [key, value] of Object.entries(init.query)) {
                      if (value == null) continue
                      if (Array.isArray(value)) value.forEach(v => { if (v != null) qs.append(key, String(v)) })
                      else qs.append(key, String(value))
                    }
                    const text = qs.toString()
                    if (text) url += (url.includes('?') ? '&' : '?') + text
                  }
                  const headers = { Accept: 'application/json', ...options.headers }
                  for (const [key, value] of Object.entries(init.headers ?? {})) if (value != null) headers[key] = value
                  if (init.body !== undefined) headers['Content-Type'] = 'application/json'
                  const token = await options.getToken?.()
                  if (token) headers.Authorization = `Bearer ${token}`
                  const res = await send(url, { method, headers, body: init.body === undefined ? undefined : JSON.stringify(init.body) })
                  const text = await res.text()
                  let data = undefined
                  if (text) { try { data = JSON.parse(text) } catch { data = text } }
                  if (res.status === 401) options.onUnauthorized?.()
                  if (!res.ok) throw new ApiError(res.status, data)
                  return data
                }

                return {

              """);
        foreach (var (group, calls) in Calls(c, names, ts))
        {
            sb.Append($"    {group}: {{\n");
            foreach (var call in calls)
            {
                if (call.Doc is not null) sb.Append($"      /** {call.Doc} */\n");
                var init = new List<string>();
                if (call.HasQuery) init.Add("query");
                if (call.HasBody) init.Add("body");
                if (call.HasHeaders) init.Add("headers");
                var initArg = init.Count > 0 ? ", { " + string.Join(", ", init) + " }" : "";
                var generic = ts ? $"<{call.ReturnType}>" : "";
                sb.Append($"      {call.Name}: ({call.Signature}) => request{generic}('{call.Method}', {call.UrlExpr}{initArg}),\n");
            }
            sb.Append("    },\n");
        }
        sb.Append("  }\n}\n");
        if (ts) sb.Append("\nexport type ApiClient = ReturnType<typeof createApiClient>\n");
        return sb.ToString();
    }

    /// <summary>Ready-to-use client instance. Created once; it's yours to change (token storage, address).</summary>
    private static string FetchIndex(string env, bool ts, bool auth)
    {
        var sb = new StringBuilder();
        sb.Append("// Your API client. QosriStudio created this file once and won't overwrite it, so change it as you like.\n");
        sb.Append("import { createApiClient } from './api-client'\n\n");
        if (auth)
        {
            sb.Append("const TOKEN_KEY = 'access_token'\n\n");
            sb.Append($"export function setToken(token{(ts ? ": string | null" : "")}) {{\n  if (token) localStorage.setItem(TOKEN_KEY, token)\n  else localStorage.removeItem(TOKEN_KEY)\n}}\n\n");
        }
        sb.Append("export const api = createApiClient({\n");
        sb.Append($"  baseUrl: {env} ?? '',\n");
        if (auth)
        {
            sb.Append("  getToken: () => (typeof localStorage === 'undefined' ? null : localStorage.getItem(TOKEN_KEY)),\n");
            sb.Append("  onUnauthorized: () => setToken(null),\n");
        }
        sb.Append("})\n\nexport * from './api-client'\n");
        return sb.ToString();
    }

    // ------------------------------------------------------------------ Angular service

    private static string AngularService(ApiContract c, Dictionary<string, string> names, string? envImport, string? envProperty, string apiName)
    {
        var used = new SortedSet<string>(StringComparer.Ordinal);
        var groups = Calls(c, names, true);
        foreach (var (_, calls) in groups)
            foreach (var call in calls)
                foreach (Match m in Regex.Matches(call.Signature + " " + call.ReturnType, @"\b[A-Z][A-Za-z0-9_]*\b"))
                    if (names.ContainsValue(m.Value)) used.Add(m.Value);
        var sb = new StringBuilder();
        sb.Append("/* eslint-disable */\n").Append(string.Format(Banner, apiName));
        sb.Append("import { Inject, Injectable, InjectionToken, Optional } from '@angular/core';\n");
        sb.Append("import { HttpClient, HttpParams } from '@angular/common/http';\n");
        sb.Append("import { Observable } from 'rxjs';\n");
        if (used.Count > 0) sb.Append($"import {{ {string.Join(", ", used)} }} from './api.models';\n");
        if (envImport is not null) sb.Append($"import {{ environment }} from '{envImport}';\n");
        sb.Append("\nexport * from './api.models';\n\n");
        sb.Append("/** Address of the API. Provide it in your app config, e.g. { provide: API_BASE_URL, useValue: 'https://localhost:5001' }. */\n");
        sb.Append(envImport is not null && envProperty is not null
            ? $"export const API_BASE_URL = new InjectionToken<string>('API_BASE_URL', {{ providedIn: 'root', factory: () => (environment as any).{envProperty} ?? '' }});\n\n"
            : "export const API_BASE_URL = new InjectionToken<string>('API_BASE_URL');\n\n");
        sb.Append("""
            function toParams(query?: object): HttpParams {
              let params = new HttpParams();
              for (const [key, value] of Object.entries(query ?? {})) {
                if (value == null) continue;
                if (Array.isArray(value)) value.forEach(v => { if (v != null) params = params.append(key, String(v)); });
                else params = params.set(key, String(value));
              }
              return params;
            }

            function toHeaders(headers?: object): Record<string, string> {
              const result: Record<string, string> = {};
              for (const [key, value] of Object.entries(headers ?? {})) if (value != null) result[key] = String(value);
              return result;
            }

            /** Typed access to every endpoint of the API. Sign-in tokens are added by an HTTP interceptor, as usual in Angular. */
            @Injectable({ providedIn: 'root' })
            export class ApiService {
              private readonly baseUrl: string;

              constructor(private readonly http: HttpClient, @Optional() @Inject(API_BASE_URL) baseUrl?: string) {
                this.baseUrl = (baseUrl ?? '').replace(/\/+$/, '');
              }

            """);
        foreach (var (group, calls) in groups)
        {
            sb.Append($"  readonly {group} = {{\n");
            foreach (var call in calls)
            {
                if (call.Doc is not null) sb.Append($"    /** {call.Doc} */\n");
                var opts = new List<string>();
                if (call.HasQuery) opts.Add("params: toParams(query)");
                if (call.HasHeaders) opts.Add("headers: toHeaders(headers)");
                var o = opts.Count > 0 ? "{ " + string.Join(", ", opts) + " }" : null;
                var url = "`${this.baseUrl}" + call.UrlExpr[1..];
                var rt = call.ReturnType;
                var expr = call.Method switch
                {
                    "GET" => $"this.http.get<{rt}>({url}{(o is null ? "" : ", " + o)})",
                    "DELETE" => $"this.http.delete<{rt}>({url}{(o is null ? "" : ", " + o)})",
                    "POST" or "PUT" or "PATCH" => $"this.http.{call.Method.ToLowerInvariant()}<{rt}>({url}, {(call.HasBody ? "body" : "null")}{(o is null ? "" : ", " + o)})",
                    _ => $"this.http.request<{rt}>('{call.Method}', {url}, {{ {(call.HasBody ? "body, " : "")}{string.Join(", ", opts)} }})",
                };
                sb.Append($"    {call.Name}: ({call.Signature}): Observable<{rt}> => {expr},\n");
            }
            sb.Append("  };\n\n");
        }
        sb.Length -= 1;
        sb.Append("}\n");
        return sb.ToString();
    }
}
